def get_all_lessons():
    result = []
    for mod_name, mod_data in CURRICULUM.items():
        for lesson in mod_data.get("lessons", []) + mod_data.get("phonics_lessons", []):
            result.append({"module": mod_name, "display": f"{mod_name} — {lesson['name']}", **lesson})
